import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import assert from "node:assert/strict";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(here, "..");
const api = fs.readFileSync(path.join(root, "src", "api.js"), "utf8");
const care = fs.readFileSync(path.join(root, "src", "careScreens.jsx"), "utf8");
const main = fs.readFileSync(path.join(root, "src", "main.jsx"), "utf8");

test("clinical notes use only Doctor-scoped APIs with optimistic version checks", () => {
  assert.ok(api.includes("/v1/dental/doctor/patients/${encodeURIComponent(patientId)}/clinical-notes"));
  assert.ok(api.includes("/v1/dental/doctor/clinical-notes/${encodeURIComponent(noteId)}"));
  assert.ok(care.includes("expected_version: note.version"));
  assert.ok(care.includes("Patient access is not enabled"));
  assert.ok(care.includes("Clinical notes are not generated by AI."));
  assert.ok(!api.includes("/v1/dental/patient/"));
  assert.ok(!api.includes("patientClinicalNotes"));
});

test("clinic communication uses only the authenticated Doctor message routes", () => {
  assert.ok(api.includes("/v1/dental/doctor/patients/${encodeURIComponent(patientId)}/messages"));
  assert.ok(api.includes("doctorMessages:"));
  assert.ok(api.includes("sendDoctorMessage:"));
  assert.ok(!api.includes("patientMessages"));
  assert.ok(!api.includes("sendPatientMessage"));
  assert.ok(care.includes("dentalApi.doctorMessages(authToken, recordId)"));
  assert.ok(care.includes("dentalApi.sendDoctorMessage(authToken, recordId"));
  assert.ok(!care.includes("dentalApi.patientMessages"));
  assert.ok(!care.includes("dentalApi.sendPatientMessage"));
  assert.ok(care.includes("A private conversation inside the authenticated Doctor workspace."));
});

test("clinical navigation remains inside the Doctor workspace", () => {
  assert.ok(main.includes("const doctorNav = ["));
  assert.ok(main.includes('["notes", "Clinical notes", FileText]'));
  assert.ok(main.includes('["files", "Private documents", FileText]'));
  assert.ok(main.includes('["messages", "Patient messages", MessageCircle]'));
  assert.ok(!main.includes("PatientCareManagement"));
  assert.ok(!main.includes("patientClinicalNotes"));
});

test("patient-specific sharing remains disabled and legacy flags are ignored", () => {
  assert.ok(care.includes("Patient sharing is not enabled"));
  assert.ok(care.includes("legacy visibility flag is ignored"));
  assert.ok(care.includes("No patient access is available"));
  assert.ok(!/patient_visible\s*:\s*!/.test(care));
  assert.ok(!api.includes("setDocumentVisibility"));
  assert.ok(!/createPatientShare|patientShareLink|sharePatientRecord/.test(care + api));
});

test("patient-facing diagnosis and clinical AI are absent", () => {
  assert.ok(main.includes("Patient-facing AI diagnosis and self-diagnosis are not available."));
  assert.ok(!/patient.*(diagnos|triage|clinical recommendation)/i.test(care));
  assert.ok(!/patientAI|patient-ai|patientClinicalIntelligence/i.test(api));
});

test("Doctor clinical state is cleared when the selected patient or session changes", () => {
  assert.ok(care.includes("setNotes([])"));
  assert.ok(care.includes("setDrafts({})"));
  assert.ok(care.includes('setLoadedScope("")'));
  assert.ok(care.includes("setPlans([])"));
  assert.ok(care.includes("setInvoices([])"));
  assert.ok(care.includes("setDocuments([])"));
  assert.ok(care.includes("setMessages([])"));
  assert.ok(care.includes('setDraft("")'));
});

test("public patient account and linked-record API methods are absent from the shipped client", () => {
  assert.ok(!/\/v1\/dental\/patient\//.test(api));
  assert.ok(!/patientClinicalNotes|patientMessages|sendPatientMessage|patientLinkedRecords/.test(api));
});
